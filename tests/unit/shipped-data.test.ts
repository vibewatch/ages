import { readFileSync } from 'node:fs';
import { describe, expect, it } from 'vitest';
import { pruneShapes } from '../../scripts/prune-shapes.ts';
import { IMPORTED_SNAPSHOTS } from '../../src/shared/data/corpus.ts';
import { SNAPSHOTS } from '../../src/shared/data/territories.ts';

describe('shipped map data', () => {
  const store = JSON.parse(readFileSync('public/data/atlas/shapes.json', 'utf8'));
  const own = JSON.parse(readFileSync('public/data/atlas/own.json', 'utf8'));

  it('is our own or public domain: no imported phases or prefecture layers remain', () => {
    expect(IMPORTED_SNAPSHOTS).toEqual([]);
    expect(Object.keys(store.snaps).every(id => id.startsWith('x_'))).toBe(true);
    for (const s of Object.values(store.snaps) as { g: unknown[]; f: unknown[] }[]) { expect(s.g).toEqual([]); expect(s.f).toEqual([]); }
    expect(String(store.source.license)).toMatch(/public domain/);
    expect(String(own.source.license)).toMatch(/own data/);
    // every map the app shows is generated by us, or one of our curated maps
    for (const s of SNAPSHOTS) expect(!s.shapes || s.own || s.shapes.startsWith('x_'), s.id).toBe(true);
  });

  it('builds keep the shapes the app shows', () => {
    const keep = new Set(SNAPSHOTS.filter(s => s.shapes && !s.own).map(s => s.shapes!));
    const out = pruneShapes(store, keep);
    for (const id of keep) expect(out.snaps[id], id).toBeDefined();
    expect(out.rings.filter(Boolean).length).toBeGreaterThan(100);
  });
});
